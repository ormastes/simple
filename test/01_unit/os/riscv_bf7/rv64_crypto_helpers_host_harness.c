static int expect_hex(const char *label, spl_i64 arr, const uint8_t *expected, size_t n) {
    if (!IS_HEAP(arr)) {
        fprintf(stderr, "FAIL %s: non-heap return 0x%llx\n", label, (unsigned long long)arr);
        return 1;
    }
    HostMockArray *a = (HostMockArray *)DECODE_PTR(arr);
    if ((size_t)a->len != n) {
        fprintf(stderr, "FAIL %s: len=%llu expected=%zu\n", label, (unsigned long long)a->len, n);
        return 1;
    }
    for (size_t i = 0; i < n; i++) {
        uint8_t got = read_mock_byte(a, i);
        if (got != expected[i]) {
            fprintf(stderr, "FAIL %s: byte[%zu]=0x%02x expected=0x%02x\n", label, i, got, expected[i]);
            return 1;
        }
    }
    printf("PASS %s (%zu bytes)\n", label, n);
    return 0;
}

